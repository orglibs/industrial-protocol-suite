enum AppLanguage {
  arSA('ar-SA', 'العربية', isRtl: true),
  deDE('de-DE', 'Deutsch'),
  enUS('en-US', 'English'),
  esES('es-ES', 'Español'),
  frFR('fr-FR', 'Français'),
  hiIN('hi-IN', 'हिन्दी'),
  idID('id-ID', 'Bahasa Indonesia'),
  itIT('it-IT', 'Italiano'),
  jaJP('ja-JP', '日本語'),
  koKR('ko-KR', '한국어'),
  plPL('pl-PL', 'Polski'),
  ptBR('pt-BR', 'Português (Brasil)'),
  ruRU('ru-RU', 'Русский'),
  thTH('th-TH', 'ไทย'),
  trTR('tr-TR', 'Türkçe'),
  viVN('vi-VN', 'Tiếng Việt'),
  zhCN('zh-CN', '简体中文'),;

  final String code;
  final String label;
  final bool isRtl;

  const AppLanguage(this.code, this.label, {{this.isRtl = false}});

  static AppLanguage fromSystem() {
    try {
      final sysLocale = WidgetsBinding.instance.platformDispatcher.locale;
      final lang = sysLocale.languageCode.toLowerCase();
      final country = sysLocale.countryCode?.toUpperCase();

      for (final l in AppLanguage.values) {
        final parts = l.code.split('-');
        if (parts[0].toLowerCase() == lang) {
          if (country != null && parts.length > 1 && parts[1] == country) {
            return l;
          }
        }
      }
      for (final l in AppLanguage.values) {
        if (l.code.split('-')[0].toLowerCase() == lang) {
          return l;
        }
      }
    } catch (_) {}
    return AppLanguage.enUS;
  }
}

