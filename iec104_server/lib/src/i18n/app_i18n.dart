enum AppLanguage {
  arSA('ar-SA', 'العربية (ar-SA)', isRtl: true),
  deDE('de-DE', 'Deutsch (de-DE)'),
  enUS('en-US', 'English (en-US)'),
  esES('es-ES', 'Español (es-ES)'),
  frFR('fr-FR', 'Français (fr-FR)'),
  hiIN('hi-IN', 'हिन्दी (hi-IN)'),
  idID('id-ID', 'Bahasa Indonesia (id-ID)'),
  itIT('it-IT', 'Italiano (it-IT)'),
  jaJP('ja-JP', '日本語 (ja-JP)'),
  koKR('ko-KR', '한국어 (ko-KR)'),
  plPL('pl-PL', 'Polski (pl-PL)'),
  ptBR('pt-BR', 'Português (pt-BR)'),
  ruRU('ru-RU', 'Русский (ru-RU)'),
  thTH('th-TH', 'ไทย (th-TH)'),
  trTR('tr-TR', 'Türkçe (tr-TR)'),
  viVN('vi-VN', 'Tiếng Việt (vi-VN)'),
  zhCN('zh-CN', '简体中文 (zh-CN)'),;

  final String code;
  final String label;
  final bool isRtl;

  const AppLanguage(this.code, this.label, {this.isRtl = false});

  static AppLanguage fromSystem() {
    try {
      final sysLocale = WidgetsBinding.instance.platformDispatcher.locale;
      final lang = sysLocale.languageCode.toLowerCase();
      final country = sysLocale.countryCode?.toUpperCase();

      for (final l in AppLanguage.values) {
        final parts = l.code.split('-');
        if (parts[0].toLowerCase() == lang) {
          if (country != null && parts.length > 1 && parts[1] == country) {
            return l;
          }
        }
      }
      for (final l in AppLanguage.values) {
        if (l.code.split('-')[0].toLowerCase() == lang) {
          return l;
        }
      }
    } catch (_) {}
    return AppLanguage.enUS;
  }
}

